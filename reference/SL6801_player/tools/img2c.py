"""Convert a PNG to a C header with an LVGL v8 lv_img_dsc_t in the firmware's pixel format.

Usage: img2c.py input.png output.h symbol_name
Pixels with alpha < 128 become the chroma key (pure green), making the image chroma-keyed;
otherwise it is plain true color. Colors are RGB565 with bytes swapped (LV_COLOR_16_SWAP=1).
"""
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from assets import encode_image  # noqa: E402


def main():
    src, out, name = sys.argv[1:4]
    im = Image.open(src).convert("RGBA")
    cf = 6 if any(a < 128 for a in im.getchannel("A").tobytes()) else 4
    data = encode_image(im, cf)
    w, h = im.size
    lines = [f"/* Generated by tools/img2c.py from {os.path.basename(src)} */", "#pragma once",
             '#include "fw.h"', "", f"static const uint8_t {name}_data[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("\t" + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines += ["};", "",
              f"static const lv_img_dsc_t {name} = {{",
              f"\t.header = LV_IMG_HEADER({'LV_IMG_CF_TRUE_COLOR_CHROMA_KEYED' if cf == 6 else 'LV_IMG_CF_TRUE_COLOR'}, {w}, {h}),",
              f"\t.data_size = sizeof({name}_data),",
              f"\t.data = {name}_data,",
              "};", ""]
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{out}: {w}x{h} {'chroma-keyed' if cf == 6 else 'true color'}, {len(data)} bytes")


if __name__ == "__main__":
    main()
